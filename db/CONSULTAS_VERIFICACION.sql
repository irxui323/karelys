SELECT USER AS ESQUEMA_ACTUAL FROM DUAL;
SELECT COUNT(*) AS TABLAS FROM USER_TABLES;
SELECT OBJECT_TYPE, STATUS, COUNT(*) AS TOTAL
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN ('PROCEDURE','FUNCTION','TRIGGER','VIEW')
GROUP BY OBJECT_TYPE,STATUS ORDER BY OBJECT_TYPE,STATUS;
SELECT TABLE_NAME,PARTITIONED FROM USER_TABLES
WHERE TABLE_NAME IN ('AUDITORIA','SESION_USUARIO');
SELECT NOMBRE,ESTADO FROM ROL ORDER BY NOMBRE;
SELECT NOMBRE,VALOR FROM PARAMETRO_SISTEMA
WHERE NOMBRE IN ('COMISION_DOCTOR','COMISION_GESTORA','BLOQUEO_MINUTOS','SESION_MINUTOS');
SELECT NAME,TYPE,LINE,TEXT FROM USER_ERRORS ORDER BY NAME,LINE;
