    V_ROL VARCHAR2(40);
    V_CITA CITA%ROWTYPE;
    V_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_CONSULTORIO_ANTERIOR CITA.ID_CONSULTORIO%TYPE;
    V_ESTADO_DOCUMENTACION DOCTOR.ESTADO_DOCUMENTACION%TYPE;
