    OPEN C_PENDIENTE;
    FETCH C_PENDIENTE INTO P_ID_NOTIFICACION, P_TIPO,
                           P_DESTINATARIO, P_CODIGO_EVENTO, V_INTENTOS;
    IF C_PENDIENTE%NOTFOUND THEN
        CLOSE C_PENDIENTE;
        DBMS_OUTPUT.PUT_LINE('No hay notificaciones disponibles.');
        RETURN;
    END IF;

    P_INTENTO := V_INTENTOS + 1;
    UPDATE NOTIFICACION_SALIENTE
       SET ESTADO = 'PENDIENTE',
           INTENTOS = P_INTENTO,
           ULTIMO_ERROR = NULL,
           FECHA_PROXIMO_INTENTO = CAST(SYSTIMESTAMP AS TIMESTAMP)
                 + NUMTODSINTERVAL(10,'MINUTE')
     WHERE ID_NOTIFICACION = P_ID_NOTIFICACION;

    CLOSE C_PENDIENTE;
    DBMS_OUTPUT.PUT_LINE('Evento tomado: ' || P_CODIGO_EVENTO);
    DBMS_OUTPUT.PUT_LINE('COMMIT ANTES de pedir el envio externo.');
EXCEPTION
    WHEN OTHERS THEN
        IF C_PENDIENTE%ISOPEN THEN
            CLOSE C_PENDIENTE;
        END IF;
        ROLLBACK TO SV_TOMAR_NOTIFICACION;
        RAISE;
END SP_TOMAR_NOTIFICACION;~');
    instalar('SP_REGISTRAR_RESULTADO_ENVIO', 'PROCEDURE', q'~CREATE OR REPLACE PROCEDURE SP_REGISTRAR_RESULTADO_ENVIO (
    P_ID_USUARIO       IN USUARIO.ID_USUARIO%TYPE,
    P_ID_NOTIFICACION  IN NOTIFICACION_SALIENTE.ID_NOTIFICACION%TYPE,
    P_INTENTO          IN NOTIFICACION_SALIENTE.INTENTOS%TYPE,
    P_EXITO            IN CHAR,
