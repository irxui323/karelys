BEGIN
    SAVEPOINT SV_RESULTADO_ENVIO;

    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);
    IF V_ROL <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20710,
            'Solo administracion puede registrar resultados del correo.');
    END IF;

    IF P_EXITO IS NULL OR P_EXITO NOT IN ('S','N') THEN
        RAISE_APPLICATION_ERROR(-20711, 'P_EXITO debe ser S o N.');
    END IF;

    SELECT ESTADO, INTENTOS
      INTO V_ESTADO, V_INTENTO_ACTUAL
      FROM NOTIFICACION_SALIENTE
     WHERE ID_NOTIFICACION = P_ID_NOTIFICACION
     FOR UPDATE;

    IF V_ESTADO <> 'PENDIENTE' OR
       P_INTENTO IS NULL OR P_INTENTO <> V_INTENTO_ACTUAL OR
       V_INTENTO_ACTUAL = 0 THEN
        RAISE_APPLICATION_ERROR(-20712,
            'El intento ya cambio o fue registrado anteriormente.');
    END IF;

