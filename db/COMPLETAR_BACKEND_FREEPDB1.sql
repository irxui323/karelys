IS
    TYPE T_IDS IS TABLE OF CITA.ID_CITA%TYPE;
    V_IDS T_IDS;
BEGIN
    P_TOTAL := 0;
    SAVEPOINT SV_MARCAR_PERDIDAS;

    UPDATE CITA C
       SET ESTADO = 'PERDIDA'
     WHERE C.ESTADO = 'REPROGRAMADA'
       AND C.REPROGRAMACIONES = 1
       AND NOT EXISTS (
           SELECT 1 FROM ASISTENCIA A
            WHERE A.ID_CITA = C.ID_CITA
       )
       AND EXISTS (
           SELECT 1 FROM FRANJA_HORARIA F
            WHERE F.ID_FRANJA = C.ID_FRANJA
              AND CAST(C.FECHA_CITA AS TIMESTAMP)
                    + NUMTODSINTERVAL(
                        TO_NUMBER(SUBSTR(F.HORA_FIN,1,2))*60
                        + TO_NUMBER(SUBSTR(F.HORA_FIN,4,2)),
                        'MINUTE') <= CAST(SYSTIMESTAMP AS TIMESTAMP)
       )
    RETURNING ID_CITA BULK COLLECT INTO V_IDS;

    P_TOTAL := V_IDS.COUNT;

    FOR I IN 1..V_IDS.COUNT LOOP
        INSERT INTO AUDITORIA (
            TABLA_AFECTADA, ID_REGISTRO, ACCION,
            DETALLE, ESTADO_ANTERIOR, ESTADO_NUEVO, ORIGEN
        ) VALUES (
            'CITA', V_IDS(I), 'PERDIDA',
            'Reprogramada sin asistencia tras finalizar su turno',
            'REPROGRAMADA', 'PERDIDA', 'SISTEMA'
        );
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Citas reprogramadas perdidas: ' || P_TOTAL);
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SV_MARCAR_PERDIDAS;
        RAISE;
END SP_MARCAR_CITAS_PERDIDAS;~');
